import { afterEach, beforeEach, describe, expect, it, vi } from "vitest";
import { APPROVAL_LOGOS, buildFooterCss, buildFooterSvg, installPrintFooter, refreshPrintFooter } from "./printFooter";

const sizes = APPROVAL_LOGOS.map((l) => ({ src: l.src, w: 100, h: 50 }));

describe("margin-box footer content", () => {
  it("draws all seven approval logos, the label and the generated-by line", () => {
    const svg = buildFooterSvg(sizes, "07 Nov 2026, 08:00 PM");
    expect(svg.match(/<image /g)).toHaveLength(7);
    expect(svg).toContain("APPROVALS");
    expect(svg).toContain("Generated by HMZC-MICMS");
    expect(svg).toContain("Printed 07 Nov 2026, 08:00 PM");
    expect(svg).toContain('width="680"');
  });

  it("escapes the text it embeds", () => {
    expect(buildFooterSvg(sizes, "a < b & c")).toContain("a &lt; b &amp; c");
  });

  it("lays the logos out left to right without overlapping each other", () => {
    const svg = buildFooterSvg(sizes, "x");
    const xs = [...svg.matchAll(/<image x="(\d+)" y="22" width="(\d+)"/g)].map((m) => [Number(m[1]), Number(m[2])]);
    for (let i = 1; i < xs.length; i++) expect(xs[i][0]).toBeGreaterThanOrEqual(xs[i - 1][0] + xs[i - 1][1]);
  });

  it("is delivered as a bottom-centre @page margin box with room for it", () => {
    const css = buildFooterCss(buildFooterSvg(sizes, "x"));
    expect(css).toContain("@page");
    expect(css).toContain("@bottom-center");
    expect(css).toContain("margin-bottom: 14mm");
    expect(css).toContain('content: url("data:image/svg+xml;charset=utf-8,');
  });
});

describe("installPrintFooter", () => {
  const RealImage = globalThis.Image;
  beforeEach(() => {
    // jsdom's CSS parser can't read page-margin boxes (@page { @bottom-center }),
    // which real browsers do; it reports that on the console — not a failure.
    vi.spyOn(console, "error").mockImplementation(() => {});
    // jsdom never loads images — pretend every logo decodes instantly.
    class FakeImage {
      naturalWidth = 100;
      naturalHeight = 50;
      onload: (() => void) | null = null;
      set src(_v: string) {
        queueMicrotask(() => this.onload?.());
      }
    }
    vi.stubGlobal("Image", FakeImage);
  });
  afterEach(() => {
    vi.restoreAllMocks();
    vi.stubGlobal("Image", RealImage);
    document.getElementById("hmzc-print-footer")?.remove();
    document.documentElement.removeAttribute("data-hmzc-footer");
  });

  it("adds the @page footer and flags the page, then removes both when the preview goes away", async () => {
    const dispose = installPrintFooter();
    await new Promise((r) => setTimeout(r, 0));
    const style = document.getElementById("hmzc-print-footer");
    expect(style?.textContent).toContain("@bottom-center");
    expect(document.documentElement.getAttribute("data-hmzc-footer")).toBe("margin");
    dispose();
    expect(document.getElementById("hmzc-print-footer")).toBeNull();
    expect(document.documentElement.hasAttribute("data-hmzc-footer")).toBe(false);
  });

  it("stays installed until the LAST preview is removed", async () => {
    const a = installPrintFooter();
    const b = installPrintFooter();
    await new Promise((r) => setTimeout(r, 0));
    a();
    expect(document.getElementById("hmzc-print-footer")).not.toBeNull();
    b();
    expect(document.getElementById("hmzc-print-footer")).toBeNull();
  });

  it("keeps a decoded copy of the footer image alive so the first print does not wait for it", async () => {
    const dispose = installPrintFooter();
    await new Promise((r) => setTimeout(r, 0));
    const holder = document.getElementById("hmzc-print-footer-img") as HTMLImageElement | null;
    expect(holder).not.toBeNull();
    expect(holder!.getAttribute("src")).toContain("data:image/svg+xml");
    // the held image is the very one the @page rule points at
    const css = document.getElementById("hmzc-print-footer")!.textContent || "";
    expect(css).toContain(holder!.getAttribute("src")!);
    dispose();
    expect(document.getElementById("hmzc-print-footer-img")).toBeNull();
  });

  it("does NOT rewrite the footer when printing starts (a fresh image there is the not-yet-loaded case)", async () => {
    const dispose = installPrintFooter();
    await new Promise((r) => setTimeout(r, 0));
    const before = document.getElementById("hmzc-print-footer")!.textContent;
    window.dispatchEvent(new Event("beforeprint"));
    expect(document.getElementById("hmzc-print-footer")!.textContent).toBe(before);
    dispose();
  });

  it("refreshPrintFooter swaps in a freshly stamped footer only after its image is ready", async () => {
    vi.useFakeTimers({ toFake: ["Date"] });
    vi.setSystemTime(new Date("2026-11-07T20:00:00"));
    const dispose = installPrintFooter();
    await new Promise((r) => setTimeout(r, 0));
    const first = document.getElementById("hmzc-print-footer")!.textContent;
    vi.setSystemTime(new Date("2026-11-07T20:09:00"));
    await refreshPrintFooter();
    const second = document.getElementById("hmzc-print-footer")!.textContent;
    expect(second).not.toBe(first);
    expect(decodeURIComponent(second || "")).toContain("08:09");
    expect(document.getElementById("hmzc-print-footer-img-next")).toBeNull(); // no leftover staging image
    dispose();
    vi.useRealTimers();
  });
});
