// The approvals footer, drawn in the PRINT PAGE'S OWN bottom margin
// (a CSS page-margin box, `@page { @bottom-center { ... } }`).
//
// Why not just a footer element in the page: every in-page way of putting
// the footer at the bottom of every printed page failed in real use.
//   - a table <tfoot> always prints, but sits right after the content, so on
//     the last page of a section it floats up the page and "jumps";
//   - `position: fixed; bottom: 0` pinned it correctly in every print I could
//     reproduce, yet two fire-equipment certificates printed on the user's own
//     Chrome came out with no footer at all (the pinned element was simply not
//     drawn), so it cannot be trusted.
// A margin box belongs to the page, not to the document flow: it is drawn at
// the same spot on every page, whatever the content, scroll position or
// layout. Its content here is ONE SVG image (logos + text), since a margin box
// cannot hold arbitrary markup.
//
// The in-page footer (tfoot) stays in the markup as the fallback and as the
// on-screen footer; CSS hides it in print only once this has installed (the
// html[data-hmzc-footer="margin"] flag) and only where the browser supports
// margin boxes — so a browser without them still prints a footer.
import {
  ABS_LOGO_DATA_URI,
  ANPG_LOGO_DATA_URI,
  BUREAU_VERITAS_LOGO_DATA_URI,
  CRALOG_LOGO_DATA_URI,
  DNV_LOGO_DATA_URI,
  INEFOP_LOGO_DATA_URI,
  ISO_LOGO_DATA_URI,
} from "../assets/approvalLogos";
import { APP_BUILD_VERSION } from "../data/appVersion";

export const APPROVAL_LOGOS = [
  { src: ABS_LOGO_DATA_URI, alt: "ABS" },
  { src: DNV_LOGO_DATA_URI, alt: "DNV" },
  { src: BUREAU_VERITAS_LOGO_DATA_URI, alt: "Bureau Veritas" },
  { src: CRALOG_LOGO_DATA_URI, alt: "CRALOG" },
  { src: INEFOP_LOGO_DATA_URI, alt: "INEFOP" },
  { src: ISO_LOGO_DATA_URI, alt: "ISO" },
  { src: ANPG_LOGO_DATA_URI, alt: "ANPG" },
];

const STYLE_ID = "hmzc-print-footer";
const FLAG = "data-hmzc-footer";
const WIDTH = 680; // px — fits the printable width of both A4 and US Letter
const HEIGHT = 62;
const LOGO_H = 24;
const GAP = 16;
const MUTED = "#6B7480";
const LINE = "#E4E7E9";

type LogoSize = { src: string; w: number; h: number };

function loadSize(src: string): Promise<LogoSize> {
  return new Promise((resolve) => {
    const img = new Image();
    img.onload = () => resolve({ src, w: img.naturalWidth || 1, h: img.naturalHeight || 1 });
    img.onerror = () => resolve({ src, w: 1, h: 1 });
    img.src = src;
  });
}

export function printedAtLabel(now = new Date()): string {
  return now.toLocaleString(undefined, { day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" });
}

const esc = (s: string) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;");

/** The footer as a standalone SVG document (exported for tests). */
export function buildFooterSvg(sizes: LogoSize[], printedAt: string): string {
  let x = 0;
  const images = sizes
    .map((l) => {
      const w = Math.max(8, Math.round((l.w / l.h) * LOGO_H));
      const out = `<image x="${x}" y="22" width="${w}" height="${LOGO_H}" preserveAspectRatio="xMidYMid meet" href="${l.src}"/>`;
      x += w + GAP;
      return out;
    })
    .join("");
  return (
    `<svg xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink" width="${WIDTH}" height="${HEIGHT}" viewBox="0 0 ${WIDTH} ${HEIGHT}">` +
    `<line x1="0" y1="1" x2="${WIDTH}" y2="1" stroke="${LINE}" stroke-width="1"/>` +
    `<text x="0" y="14" font-family="Helvetica, Arial, sans-serif" font-size="8.5" letter-spacing="0.4" fill="${MUTED}">APPROVALS</text>` +
    images +
    `<text x="${WIDTH}" y="58" text-anchor="end" font-family="Helvetica, Arial, sans-serif" font-size="7.5" fill="${MUTED}">${esc(`Generated by HMZC-MICMS (v${APP_BUILD_VERSION}) · Printed ${printedAt}`)}</text>` +
    `</svg>`
  );
}

/** The @page rule that draws the footer in every page's bottom margin. */
export function buildFooterCss(svg: string): string {
  const url = `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
  return `@page { margin-bottom: 26mm; @bottom-center { content: url("${url}"); vertical-align: top; padding-top: 4mm; } }`;
}

let sizesPromise: Promise<LogoSize[]> | null = null;
let installed = 0;
let sizes: LogoSize[] | null = null;

function writeStyle() {
  if (!sizes) return;
  let el = document.getElementById(STYLE_ID) as HTMLStyleElement | null;
  if (!el) {
    el = document.createElement("style");
    el.id = STYLE_ID;
    document.head.appendChild(el);
  }
  el.textContent = buildFooterCss(buildFooterSvg(sizes, printedAtLabel()));
  document.documentElement.setAttribute(FLAG, "margin");
}

/**
 * Installs the margin-box footer while a certificate preview is on screen and
 * returns a function that removes it again (the @page rule is global to the
 * document, so it must not leak onto other printouts such as invoices).
 */
export function installPrintFooter(): () => void {
  installed += 1;
  const refresh = () => writeStyle(); // the "Printed <time>" stamp is fresh at print time
  if (!sizesPromise) sizesPromise = Promise.all(APPROVAL_LOGOS.map((l) => loadSize(l.src)));
  sizesPromise
    .then((s) => {
      sizes = s;
      if (installed > 0) writeStyle();
    })
    .catch(() => {
      /* leave the in-page footer (fallback) in charge */
    });
  window.addEventListener("beforeprint", refresh);
  return () => {
    installed -= 1;
    window.removeEventListener("beforeprint", refresh);
    if (installed <= 0) {
      installed = 0;
      document.getElementById(STYLE_ID)?.remove();
      document.documentElement.removeAttribute(FLAG);
    }
  };
}
